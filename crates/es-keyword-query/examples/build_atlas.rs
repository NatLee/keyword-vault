mod support;
use es_keyword_query::{Options, Query};
use serde_json::json;

fn main() {
    let specimens = [
        ("discovery", "Discovery", "Grouped alternatives, a required context, and an exclusion.", "(tea|coffee)&shop!ad"),
        ("proximity", "Phrase distance", "Slop describes term movement, not a character count.", "(apple pie ~5)&bakery"),
        ("unicode", "Full-width input", "NFKC normalization brings full-width operators into the same grammar.", "（茶｜咖啡）＆店！廣告"),
        ("nested", "Nested exclusions", "An exclusion can apply to a whole group; its children retain their own operators.", "(electric car|EV)&(review|range)!(used|toy)"),
        ("escaped", "Literal operators", "Escaped operators stay inside a term. Precise mode quotes the resulting literal.", "AT\\&T|M\\&M"),
        ("raw", "Raw Lucene terms", "Raw mode passes fields and wildcards through. It is not an escaping boundary.", "title:rust|search*"),
        ("precedence", "Written order", "No precedence is inferred. Add parentheses before mixing AND and OR in a production query.", "tea|coffee&shop"),
        ("invalid", "Find the error", "A second consecutive operator is rejected before compilation.", "tea&&coffee"),
    ];
    let data: Vec<_> = specimens
        .iter()
        .map(|(id, title, note, input)| {
            let modes: Vec<_> = [true, false]
                .into_iter()
                .map(|precise| {
                    let mut result = support::inspect(input, precise, 20);
                    let filters: Vec<_> = specimens
                        .iter()
                        .map(|(_, _, _, filter)| {
                            let options = Options {
                                precise,
                                ..Options::default()
                            };
                            match (
                                Query::parse_with(input, options.clone()),
                                Query::parse_with(filter, options),
                            ) {
                                (Ok(query), Ok(filter)) => Some(query.filtered_by(&filter)),
                                _ => None,
                            }
                        })
                        .collect();
                    result["filtered"] = json!(filters);
                    result
                })
                .collect();
            json!({"id":id, "title":title, "note":note, "input":input, "modes":modes})
        })
        .collect();
    let content = format!(
        "// Generated by cargo run --example build_atlas. Do not edit.\nwindow.ATLAS = {};\n",
        serde_json::to_string_pretty(&data).unwrap()
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/atlas-data.js");
    if std::env::args().any(|a| a == "--check") {
        assert_eq!(
            std::fs::read_to_string(path).unwrap(),
            content,
            "Regenerate the atlas fixtures"
        );
    } else {
        std::fs::write(path, content).unwrap();
    }
}
